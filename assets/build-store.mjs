/**
 * The two pictures Play asks for that Android never sees.
 *
 *   node assets/build-store.mjs
 *
 * `play-icon-512.png`  — the tile in the listing and in search results. Exactly
 *                        512 square, no transparency: Play composites it onto
 *                        its own backgrounds and an alpha channel there shows
 *                        up as a hole.
 *
 * `play-feature-graphic.png` — 1024x500, the banner across the top of the
 *                        listing. Play crops it for some surfaces and lays a
 *                        play button over the middle of it for others, so
 *                        nothing that matters goes in the centre or near an
 *                        edge: the name sits left, the trader sits right, and
 *                        the middle is background.
 *
 * Neither is generated by `npm run icons`, because neither is an app asset —
 * they are uploaded by hand to the console, once, and again only when the
 * artwork changes.
 *
 * The title is set in a heavy system sans rather than the game's own display
 * face, which is licensed and lives outside this repository (see the README).
 * If it is ever put somewhere this script can read, set FONT to it.
 */
import sharp from 'sharp';

const SOURCE = 'assets/source-icon.png';
const FONT = 'Arial Black, Segoe UI Black, Impact, sans-serif';

/* ------------------------------------------------------------ the 512 tile */

// Flattened onto the artwork's own blue rather than onto white: the drawing
// runs to its own edges, so there is nothing to flatten against except a
// colour that would show as a rim if it were wrong.
await sharp(SOURCE)
  .resize(512, 512)
  .flatten({ background: '#0044C8' })
  .png({ palette: true, colors: 256, dither: 1, effort: 10 })
  .toFile('assets/play-icon-512.png');

/* ------------------------------------------------------- the feature banner */

const W = 1024;
const H = 500;

/**
 * The trader, cut out of the square artwork.
 *
 * The drawing is 1254 square with the figure in the middle and the BUY/SELL
 * buttons across the bottom. Taking the top two thirds keeps the face, the
 * fist and the chart and leaves the buttons out — they are the icon's
 * punchline and they would be unreadable at banner height anyway.
 */
const FIGURE = { left: 210, top: 40, width: 840, height: 840 };

const figure = await sharp(SOURCE)
  .extract(FIGURE)
  .resize(H, H)
  .png()
  .toBuffer();

const background = Buffer.from(
  `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">
     <defs>
       <radialGradient id="g" cx="62%" cy="45%" r="78%">
         <stop offset="0%" stop-color="#1E74E8"/>
         <stop offset="55%" stop-color="#0044C8"/>
         <stop offset="100%" stop-color="#00307E"/>
       </radialGradient>
     </defs>
     <rect width="${W}" height="${H}" fill="url(#g)"/>
     <!-- the line a match is won on, drawn the way the game draws it -->
     <path d="M-20 430 L120 360 L220 395 L340 250 L430 300 L560 130 L700 60"
           fill="none" stroke="#FFFFFF" stroke-opacity="0.16" stroke-width="46"
           stroke-linecap="round" stroke-linejoin="round"/>
   </svg>`,
);

/**
 * The name, in two lines because one would either be small or run under the
 * trader. White on a dark stroke, which is what every piece of lettering in
 * this game wears — see the BUY and SELL buttons in the artwork.
 */
const title = Buffer.from(
  `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">
     <g font-family="${FONT}" font-weight="900" font-size="92" letter-spacing="1">
       <text x="62" y="228" fill="#0A2E63" stroke="#0A2E63" stroke-width="14"
             stroke-linejoin="round">BROKER</text>
       <text x="62" y="228" fill="#FFFFFF">BROKER</text>
       <text x="62" y="322" fill="#0A2E63" stroke="#0A2E63" stroke-width="14"
             stroke-linejoin="round">STARS</text>
       <text x="62" y="322" fill="#3FD11A">STARS</text>
     </g>
     <g font-family="${FONT}" font-weight="700" font-size="27" fill="#FFFFFF"
        fill-opacity="0.82">
       <text x="66" y="378">80 SECONDS · 3 STOCKS · 1 RIVAL</text>
     </g>
   </svg>`,
);

await sharp(background)
  .composite([
    // Bleeds off the right edge and runs the full height: a crop that stopped
    // short of both would read as a sticker laid on the background.
    { input: figure, left: 566, top: 0 },
    { input: title, left: 0, top: 0 },
  ])
  .flatten({ background: '#0044C8' })
  .png({ palette: true, colors: 256, dither: 1, effort: 10 })
  .toFile('assets/play-feature-graphic.png');

console.log('play-icon-512.png, play-feature-graphic.png');
